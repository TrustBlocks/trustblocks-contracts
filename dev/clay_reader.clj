(ns clay-reader
  "Lets Clay render a notebook that uses XTDB.

  Clay finds a notebook's comments -- its prose -- and its bare top-level
  values with parcera, a Clojure grammar generated by ANTLR 4.7. XTDB's SQL
  parser needs the ANTLR 4.13 runtime, and one JVM loads one ANTLR: under
  4.13, parcera's parser fails to load ('Could not deserialize ATN with
  version 3'). So bin/notebook replaces Clay's one parcera-based function,
  scicloj.clay.v2.read/read-by-parcera, with this one: the same notes, in
  the same shape, found with rewrite-clj, which uses no ANTLR. Clay reads
  every form with tools.reader as before.

  Remove when Clay no longer depends on parcera."
  (:require [clojure.string :as str]
            [rewrite-clj.node :as n]
            [rewrite-clj.parser :as p]
            [scicloj.clay.v2.read]))

(defn- region
  "[start-row start-col end-row end-col], columns 1-based, the end just past
  the last character -- as Clay's parcera reader gives it. rewrite-clj's
  comment nodes include their newline; that is not part of the note."
  [node text]
  (let [{:keys [row col]} (meta node)
        lines (str/split text #"\n" -1)]
    [row col
     (+ row (dec (count lines)))
     (if (= 1 (count lines)) (+ col (count text)) (inc (count (last lines))))]))

(defn read-by-rewrite-clj
  "What scicloj.clay.v2.read/read-by-parcera returns for `code`: each
  top-level comment, and each top-level string, number, symbol or keyword
  (which tools.reader gives no location for), with its region."
  [code]
  (for [node (n/children (p/parse-string-all code))
        :let [tag (n/tag node)]
        :when (#{:comment :token :multi-line} tag)
        :let [text (cond-> (n/string node) (= :comment tag) (str/replace #"\r?\n$" ""))]]
    (cond-> {:method :parcera :region (region node text) :code text}
      (= :comment tag) (assoc :comment? true))))

(defn install! []
  (alter-var-root #'scicloj.clay.v2.read/read-by-parcera (constantly read-by-rewrite-clj)))
